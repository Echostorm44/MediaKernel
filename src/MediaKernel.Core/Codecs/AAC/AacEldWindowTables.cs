// The ELD analysis windows, as literal data from ffmpeg-master/libavcodec/aactab.c.
//
// Unlike every other window in this decoder these are NOT analytic - there is no sine or
// Kaiser-Bessel formula that generates them, so they cannot be computed and have to be carried.
// They are copied out of the C source by a script rather than retyped, because 3,720 values
// transcribed by hand is 3,720 chances to be silently a little bit wrong, and a window
// multiplies every output sample.
//
// Their lengths are 4n - n/4 for n = 512 and n = 480, which is exactly the span
// imdct_and_windowing_eld indexes: the highest subscript it forms is
// (n2 - 1) + n2 + 3n - n4 = 4n - n4 - 1.

