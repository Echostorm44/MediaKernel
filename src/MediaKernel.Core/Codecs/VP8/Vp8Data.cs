    /// <summary>
    /// Get a span of 9 intra 4x4 prediction probabilities for a given (top, left) context pair.
    /// Provides row-level access into Pred4x4ProbIntra[top, left, 0..8].
    /// </summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static ReadOnlySpan<byte> Pred4x4ProbIntraSlice(int topMode, int leftMode)
    {
        // Access the 3D array as a flat span: index = (top * 10 + left) * 9
        return new ReadOnlySpan<byte>(Pred4x4ProbIntraFlat, (topMode * 10 + leftMode) * 9, 9);
    }

    // Flat backing array for Pred4x4ProbIntra (10 * 10 * 9 = 900 bytes)
    internal static readonly byte[] Pred4x4ProbIntraFlat = InitPred4x4ProbIntraFlat();

    private static byte[] InitPred4x4ProbIntraFlat()
    {
        var flat = new byte[10 * 10 * 9];
        for (int t = 0; t < 10; t++)
            for (int l = 0; l < 10; l++)
                for (int p = 0; p < 9; p++)
                    flat[(t * 10 + l) * 9 + p] = Pred4x4ProbIntra[t, l, p];
        return flat;
    }

    /// <summary>
    /// Get the DCT category extra-bit probability table for a given category (0-3).
    /// Category 0 → DctCat3Prob, Category 1 → DctCat4Prob, etc.
    /// This maps the (a<<1)+b result from the coefficient decode tree.
    /// </summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static ReadOnlySpan<byte> DctCatProb(int cat)
    {
        return cat switch
        {
            0 => DctCat3Prob,
            1 => DctCat4Prob,
            2 => DctCat5Prob,
            _ => DctCat6Prob,
        };
    }
